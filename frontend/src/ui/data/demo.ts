      return '本班 60 人，期中均分 82.4，80–89 分段人数最多。薄弱点集中在拥塞控制（42%）、子网划分（58%）与路由算法（61%）。建议下节课用 10 分钟复盘 cwnd 曲线，再安排 8 名预警学生的一对一提醒。'
